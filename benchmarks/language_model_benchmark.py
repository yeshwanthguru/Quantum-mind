"""A small robot-instruction language model against a bag-of-words encoder, and what its beliefs do downstream (simulation).

Everything is generated by a small grammar (see ``quantum_mind.cognition.corpus``), so the numbers show what each model can learn from such
rules, not how it would read people. Three encoders feed the same grounding head (attention over the camera strip):

* ``bag``: a mean of word embeddings (cannot use word order);
* ``transformer, grounding only``: the transformer trained on grounding alone;
* ``transformer + LM``: the transformer also trained to predict the next word (a language model).

Measured on fresh sentences: grounding accuracy by kind of sentence (unambiguous ones: the most likely cell is a valid referent), on conjunctions
whose colour-side combination was never seen in training, the per-word perplexity, and the closed-loop success of the one-motor VLA when its
target comes from the model's belief (corrections only). Part B fuses a two-turn dialogue (instruction, then a follow-up that sometimes
misspeaks) with Bayes, context weights and the quantum-cognition core on the language model's beliefs. Mean ± std over seeds.
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np

from quantum_mind.cognition import DialogueBelief, RobotLanguageModel, corpus as C, language_plan, make_dialogues
from quantum_mind.embodied import TinyVLA, make_dataset, run_episode

KINDS = ('simple', 'polite', 'conjunction', 'correction', 'followup')
ENCODERS = {'bag of words': dict(encoder='bag', lm_weight=0.0), 'transformer, grounding only': dict(encoder='transformer', lm_weight=0.0),
            'transformer + language modelling': dict(encoder='transformer', lm_weight=1.0)}


def grounding_accuracy(lm, us):
    us = [u for u in us if not u.ambiguous]
    b = lm.ground(us)
    return float(np.mean([np.argmax(bb) in u.valid for u, bb in zip(us, b)]))


def sign_flip_p(diff, n_perm=4000, seed=0):
    diff = np.asarray(diff, float)
    rng = np.random.default_rng(seed)
    obs = abs(diff.mean())
    signs = rng.choice([-1.0, 1.0], size=(n_perm, len(diff)))
    return float((np.sum(np.abs((signs * diff).mean(axis=1)) >= obs - 1e-15) + 1) / (n_perm + 1))


def run(quick=False):
    seeds = range(2 if quick else 3)
    steps, n_train, n_test, n_loop, n_dlg = (500, 3000, 800, 60, 600) if quick else (1500, 8000, 2000, 150, 1500)
    res = {e: dict(kinds={k: [] for k in KINDS}, heldout=[], ppl=[], loop=[], loop_rows=[]) for e in ENCODERS}
    dlg = {f: dict(loss=[], acc=[], rows=[]) for f in ('bayes', 'context weights', 'quantum core')}
    t0 = time.time()
    for seed in seeds:
        train = C.make_corpus(n_train, seed)
        test = C.make_corpus(n_test, 1000 + seed)
        held = C.make_corpus(n_test // 2, 2000 + seed, 'heldout')
        corr = [u for u in C.make_corpus(4 * n_loop, 3000 + seed) if u.kind == 'correction' and not u.ambiguous][:n_loop]
        act = TinyVLA(seed=seed).fit(make_dataset(2000, seed), steps=1500, seed=seed).act
        models = {}
        for name, kw in ENCODERS.items():
            m = RobotLanguageModel(steps=steps, seed=seed, **kw).fit(train)
            models[name] = m
            r = res[name]
            for k in KINDS:
                r['kinds'][k].append(grounding_accuracy(m, [u for u in test if u.kind == k]))
            r['heldout'].append(grounding_accuracy(m, held))
            if kw['encoder'] == 'transformer' and kw['lm_weight'] > 0:
                r['ppl'].append(m.perplexity(test))
            plan = language_plan(m, act)
            rng = np.random.default_rng(seed)
            rows = [float(run_episode(u, rng, plan)['success']) for u in corr]
            r['loop'].append(float(np.mean(rows)))
            r['loop_rows'].extend(rows)
            print('seed', seed, name, 'done %.0fs' % (time.time() - t0), flush=True)
        lm = models['transformer + language modelling']
        d_train, d_test = make_dialogues(n_dlg, seed), make_dialogues(n_dlg, 500 + seed)
        for f in dlg:
            db = DialogueBelief(lm, f, steps=300, restarts=2, seed=seed).fit(d_train)
            p = db.predict_proba(d_test)
            y = db.labels(d_test)
            nll = -np.log(p[np.arange(len(y)), y] + 1e-7)
            dlg[f]['loss'].append(float(nll.mean()))
            dlg[f]['acc'].append(float(np.mean(p.argmax(1) == y)))
            dlg[f]['rows'].extend(nll.tolist())
        print('seed', seed, 'dialogue fusion done %.0fs' % (time.time() - t0), flush=True)
    return dict(seeds=len(list(seeds)), steps=steps, n_train=n_train, n_test=n_test, n_loop=n_loop, n_dlg=n_dlg, res=res, dlg=dlg,
                params={e: RobotLanguageModel(**kw).n_params for e, kw in ENCODERS.items()})


def ms(v):
    return '%.3f ± %.3f' % (np.mean(v), np.std(v))


def to_markdown(o):
    L = ['# A small robot-instruction language model', '',
         'Simulation, sentences from a rule-based grammar of %d words. %d seeds; %d training sentences, %d test sentences, %d training steps; '
         'mean ± std over seeds. Every encoder has the same grounding head and %d parameters.' % (len(C.WORDS), o['seeds'], o['n_train'],
                                                                                              o['n_test'], o['steps'],
                                                                                              list(o['params'].values())[0]), '',
         '## A. Grounding accuracy on fresh sentences (unambiguous ones)', '',
         '| Encoder | ' + ' | '.join(KINDS) + ' | held-out combinations | perplexity |', '|---|' + '---|' * (len(KINDS) + 2)]
    for e, r in o['res'].items():
        L.append('| %s | %s | %s | %s |' % (e, ' | '.join(ms(r['kinds'][k]) for k in KINDS), ms(r['heldout']),
                                           '%.2f' % np.mean(r['ppl']) if r['ppl'] else '–'))
    L += ['', 'Held-out combinations: conjunctions such as "the blue last block" whose colour-side pair never appears in training. Perplexity is per word '
          'on fresh sentences (a model that guessed uniformly among the %d words would have %d).' % (len(C.WORDS), len(C.WORDS)), '',
          '## B. Closed loop: the one-motor VLA drives to the cell the model believes in', '',
          '%d correction sentences per seed ("go to the red one, no, the blue one"); success = final position within a quarter cell.' % o['n_loop'], '',
          '| Encoder | Success | p vs bag of words |', '|---|---|---|']
    bag = np.array(o['res']['bag of words']['loop_rows'])
    for e, r in o['res'].items():
        p = '–' if e == 'bag of words' else '%.4f' % sign_flip_p(np.array(r['loop_rows']) - bag)
        L.append('| %s | %s | %s |' % (e, ms(r['loop']), p))
    L += ['', '## C. Fusing a two-turn dialogue on the language model\'s beliefs', '',
          '%d dialogues for fitting and %d for testing per seed: an instruction (simple or ambiguous), then a follow-up ("no, the left one") that '
          'misspeaks with probability 0.25 after a clear instruction and 0.05 after an ambiguous one. That person is a classical, context-dependent '
          'noise model chosen by the author, not data. Log-loss (lower is better) and accuracy of the most likely object.' % (o['n_dlg'], o['n_dlg']), '',
          '| Fusion | Log-loss | Accuracy | p vs Bayes |', '|---|---|---|---|']
    ref = np.array(o['dlg']['bayes']['rows'])
    for f, r in o['dlg'].items():
        p = '–' if f == 'bayes' else '%.4f' % sign_flip_p(np.array(r['rows']) - ref)
        L.append('| %s | %s | %s | %s |' % (f, ms(r['loss']), ms(r['acc']), p))
    L += ['', 'The dialogue person is classical, so a quantum-like advantage is not expected here and none is claimed; the table shows that the language '
          'model\'s beliefs can feed any of the fusion rules.', '']
    return '\n'.join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--quick', action='store_true')
    ap.add_argument('--out', default='benchmarks/results/language_model')
    a = ap.parse_args()
    o = run(a.quick)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / 'benchmark_results.md').write_text(to_markdown(o))
    raw = {'kinds': {e: {k: float(np.mean(v)) for k, v in r['kinds'].items()} | {'heldout': float(np.mean(r['heldout']))} for e, r in o['res'].items()},
           'dialogue': {f: {'loss': float(np.mean(r['loss'])), 'acc': float(np.mean(r['acc']))} for f, r in o['dlg'].items()}}
    (out / 'benchmark_raw.json').write_text(json.dumps(raw, indent=1))
    print((out / 'benchmark_results.md').read_text())


if __name__ == '__main__':
    main()
