"""A small robot-instruction language model, trained from scratch, that grounds sentences in a camera strip.

:class:`RobotLanguageModel` is a decoder-only transformer (about 30k parameters at the defaults) trained on two things at once:

* **language modelling**: predict the next word of an instruction (so it can score, and complete, sentences), and
* **grounding**: read the whole sentence and say which cell of the table the speaker means, by attending over the image (the same
  attention step as :class:`~quantum_mind.embodied.TinyVLA`, with the sentence encoding as the query).

``encoder='bag'`` swaps the transformer for a mean of word embeddings with the same grounding head; it is the controlled baseline, and it
cannot tell "go to the red one, no, the blue one" from "go to the blue one, no, the red one". The result is a belief over cells, which the
rest of the library (the conformal ask gate, the action head, the quantum-cognition core) can use unchanged.

It is a toy in the honest sense: about 30 words, sentences generated by rules (see :mod:`quantum_mind.cognition.corpus`), nothing like open
language. Needs the optional ``cognition`` extra (JAX, Optax).
"""
from __future__ import annotations

import numpy as np

from .._optional import require
from . import corpus as C

jax = require('jax', extra='cognition')
optax = require('optax', extra='cognition')
import jax.numpy as jnp  # noqa: E402

__all__ = ['RobotLanguageModel', 'language_plan']


def _ln(x, g, b):
    m = x.mean(-1, keepdims=True)
    v = ((x - m) ** 2).mean(-1, keepdims=True)
    return (x - m) / jnp.sqrt(v + 1e-5) * g + b


class RobotLanguageModel:
    """A tiny language model with a grounding head.

    Parameters
    ----------
    d, n_layers, n_heads : int, optional
        Width, depth and attention heads of the transformer (defaults 32, 2, 2).
    encoder : {'transformer', 'bag'}, optional
        How a sentence becomes a query for the image attention.
    lm_weight : float, optional
        Weight of the next-word loss next to the grounding loss (0 trains grounding only).
    steps, lr, batch, seed : optional
        Optimisation settings for :meth:`fit`.
    """

    def __init__(self, d=32, n_layers=2, n_heads=2, encoder='transformer', lm_weight=1.0, steps=1500, lr=3e-3, batch=128, seed=0,
                 d_img=16):
        if encoder not in ('transformer', 'bag'):
            raise ValueError("encoder must be 'transformer' or 'bag'")
        self.d, self.n_layers, self.n_heads, self.encoder = d, n_layers, n_heads, encoder
        self.lm_weight, self.steps, self.lr, self.batch, self.seed, self.d_img = lm_weight, steps, lr, batch, seed, d_img
        self.V, self.L = len(C.WORDS), C.MAX_LEN
        self.params = self._init(jax.random.PRNGKey(seed))
        self._jit = {}

    # ---- parameters -----------------------------------------------------------------------------------------------------
    def _init(self, key):
        d, V, L = self.d, self.V, self.L
        ks = iter(jax.random.split(key, 8 + 8 * self.n_layers))
        nrm = lambda *shape: 0.1 * jax.random.normal(next(ks), shape)         # noqa: E731
        p = {'emb': nrm(V, d), 'pos': nrm(L, d), 'Wg': nrm(d, d), 'img_Wv': nrm(3, self.d_img), 'img_bv': jnp.zeros(self.d_img),
             'img_Wk': nrm(self.d_img, d), 'img_P': nrm(C.N_CELLS, d), 'lnf_g': jnp.ones(d), 'lnf_b': jnp.zeros(d)}
        p['layers'] = [{'Wq': nrm(d, d), 'Wk': nrm(d, d), 'Wv': nrm(d, d), 'Wo': nrm(d, d), 'W1': nrm(d, 4 * d), 'b1': jnp.zeros(4 * d),
                        'W2': nrm(4 * d, d), 'b2': jnp.zeros(d), 'ln1_g': jnp.ones(d), 'ln1_b': jnp.zeros(d), 'ln2_g': jnp.ones(d),
                        'ln2_b': jnp.zeros(d)} for _ in range(self.n_layers)]
        return p

    @property
    def n_params(self):
        return int(sum(np.size(v) for v in jax.tree_util.tree_leaves(self.params)))

    # ---- forward --------------------------------------------------------------------------------------------------------
    def _hidden(self, p, toks):
        B, L = toks.shape
        x = p['emb'][toks] + p['pos'][None, :L]
        H, dh = self.n_heads, self.d // self.n_heads
        mask = jnp.tril(jnp.ones((L, L), bool))[None, None]
        for lyr in p['layers']:
            h = _ln(x, lyr['ln1_g'], lyr['ln1_b'])
            q, k, v = (h @ lyr[n] for n in ('Wq', 'Wk', 'Wv'))
            split = lambda a: a.reshape(B, L, H, dh).transpose(0, 2, 1, 3)    # noqa: E731
            att = (split(q) @ split(k).transpose(0, 1, 3, 2)) / jnp.sqrt(dh)
            att = jax.nn.softmax(jnp.where(mask, att, -1e9), axis=-1)
            x = x + (att @ split(v)).transpose(0, 2, 1, 3).reshape(B, L, self.d) @ lyr['Wo']
            h = _ln(x, lyr['ln2_g'], lyr['ln2_b'])
            x = x + jax.nn.gelu(h @ lyr['W1'] + lyr['b1']) @ lyr['W2'] + lyr['b2']
        return _ln(x, p['lnf_g'], p['lnf_b'])

    def _query(self, p, toks, lens):
        if self.encoder == 'bag':
            real = (jnp.arange(toks.shape[1])[None] < lens[:, None]) & (toks > 2)           # words only (not pad, bos, eos)
            e = p['emb'][toks] * real[..., None]
            pooled = e.sum(1) / jnp.maximum(real.sum(1, keepdims=True), 1)
            return pooled @ p['Wg'], None
        h = self._hidden(p, toks)
        last = h[jnp.arange(toks.shape[0]), lens - 1]                                       # the state at <eos> has read the sentence
        return last @ p['Wg'], h

    def _belief(self, p, toks, lens, img):
        q, h = self._query(p, toks, lens)
        keys = jax.nn.relu(img @ p['img_Wv'] + p['img_bv']) @ p['img_Wk'] + p['img_P'][None]
        score = jnp.einsum('bd,bcd->bc', q, keys) / jnp.sqrt(self.d)
        return jax.nn.log_softmax(score, axis=-1), h

    def _loss(self, p, toks, lens, img, tgt):
        logb, h = self._belief(p, toks, lens, img)
        ground = -jnp.mean(logb[jnp.arange(len(tgt)), tgt])
        if h is None or self.lm_weight == 0:
            return ground
        logits = h[:, :-1] @ p['emb'].T                                                      # tied output embedding
        nxt = toks[:, 1:]
        valid = (jnp.arange(nxt.shape[1])[None] < (lens[:, None] - 1))
        lp = jax.nn.log_softmax(logits, axis=-1)
        nll = -jnp.take_along_axis(lp, nxt[..., None], axis=-1)[..., 0]
        return ground + self.lm_weight * (nll * valid).sum() / valid.sum()

    # ---- training and use -----------------------------------------------------------------------------------------------
    def fit(self, utterances):
        """Train on a list of :class:`~quantum_mind.cognition.corpus.Utterance` by minibatch Adam with cosine decay."""
        toks, lens, img, tgt = C.batch(utterances)
        # the target is a cell index; the belief is over the 16 cells of the strip
        sched = optax.cosine_decay_schedule(self.lr, self.steps)
        opt = optax.adam(sched)
        state = opt.init(self.params)
        grad = self._compiled('grad', lambda p, a, b, c, d_: jax.value_and_grad(self._loss)(p, a, b, c, d_))
        rng = np.random.default_rng(self.seed)
        p = self.params
        for _ in range(self.steps):
            i = rng.integers(0, len(tgt), self.batch)
            _, g = grad(p, toks[i], lens[i], img[i], tgt[i])
            upd, state = opt.update(g, state)
            p = optax.apply_updates(p, upd)
        self.params = p
        return self

    def _compiled(self, name, fn):
        key = (name, self.encoder, self.d, self.n_layers, self.n_heads, self.lm_weight == 0)
        if key not in RobotLanguageModel._jit_cache:
            RobotLanguageModel._jit_cache[key] = jax.jit(fn)
        return RobotLanguageModel._jit_cache[key]

    _jit_cache = {}

    def ground(self, utterances):
        """Belief over the 16 cells for each utterance (a list, or one utterance), shape ``(N, 16)``."""
        single = not isinstance(utterances, (list, tuple))
        us = [utterances] if single else list(utterances)
        toks, lens, img, _ = C.batch(us)
        fn = self._compiled('belief', lambda p, a, b, c: self._belief(p, a, b, c)[0])
        out = np.exp(np.asarray(fn(self.params, toks, lens, img)))
        return out[0] if single else out

    def ground_text(self, text, image):
        """Belief over cells for a sentence (a string of vocabulary words) and an image strip ``(16, 3)``."""
        u = C.Utterance(np.asarray(image, np.float32), text, C.encode(text), [], [], [], 0, 'free')
        return self.ground(u)

    def perplexity(self, utterances):
        """Per-word perplexity of the sentences under the language model (``<eos>`` included)."""
        toks, lens, _, _ = C.batch(utterances)
        if self.encoder == 'bag':
            raise ValueError('a bag-of-words encoder is not a language model')

        def nll(p, t, ln):
            logits = self._hidden(p, t)[:, :-1] @ p['emb'].T
            lp = jax.nn.log_softmax(logits, axis=-1)
            x = -jnp.take_along_axis(lp, t[:, 1:, None], axis=-1)[..., 0]
            v = jnp.arange(x.shape[1])[None] < (ln[:, None] - 1)
            return (x * v).sum(), v.sum()
        total, count = self._compiled('nll', nll)(self.params, toks, lens)
        return float(np.exp(float(total) / float(count)))

    def complete(self, prefix='', max_words=12):
        """Greedy completion of an instruction from a prefix (for example ``'please go to the'``)."""
        if self.encoder == 'bag':
            raise ValueError('a bag-of-words encoder is not a language model')
        toks = C.encode(prefix)[:-1]
        fn = self._compiled('next', lambda p, t, n: (self._hidden(p, t)[0, n - 1] @ p['emb'].T))
        while len(toks) < self.L:
            padded = np.zeros((1, self.L), np.int32)
            padded[0, :len(toks)] = toks
            nxt = int(np.argmax(np.asarray(fn(self.params, padded, len(toks)))))
            if nxt == C.VOCAB['<eos>'] or len(toks) - 1 >= max_words:
                break
            toks.append(nxt)
        return C.decode(toks)


def language_plan(lm, act):
    """A closed-loop plan for :func:`quantum_mind.embodied.run_episode`: ground the sentence, drive to the most likely cell.

    ``lm`` is a :class:`RobotLanguageModel` and ``act(target, theta, omega)`` is an action head such as :meth:`TinyVLA.act`. The "scene" is
    a :class:`~quantum_mind.cognition.corpus.Utterance`. Ambiguous sentences are not handled here (no ask gate): the robot picks the
    likeliest cell.
    """
    xs = C.cell_centres()

    def plan(u, rng):
        target = float(xs[int(np.argmax(lm.ground(u)))])
        return (lambda th, om: float(act(target, th, om))), 0
    return plan
