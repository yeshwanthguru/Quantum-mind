"""A synthetic corpus of robot instructions on the one-dimensional tabletop, with the ground truth behind every sentence.

The grammar is small on purpose (about 40 words) so a language model can be trained from scratch on a CPU, but it contains what
makes language more than a bag of words: *order* (a correction overrides what came before it: "go to the red one, no, the blue
one"), *synonyms* ("leftmost", "left", "first"), *politeness and filler*, *conjunction* ("the red leftmost block") and
*ambiguity* ("go to the block" with two blocks). Each utterance comes with a scene (a noisy colour strip, 2 or 3 objects), the
set of cells the sentence is true of, and the cell the speaker means.

Nothing here is real human language: the sentences are generated by rules chosen by the library's author, so results on this
corpus show what a model can learn from such rules, not how it would read people."""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np

N_CELLS = 16
COLORS = ('red', 'green', 'blue')
LEFT_WORDS = ('leftmost', 'left', 'first')
RIGHT_WORDS = ('rightmost', 'right', 'last')
VERBS = ('go', 'move', 'drive', 'head', 'reach')
PREPS = ('to', 'over to', 'towards')
NOUNS = ('block', 'one', 'object', 'thing')
CORRECTIONS = ('no', 'sorry i mean', 'i mean', 'wait')
WORDS = ('<pad>', '<bos>', '<eos>', 'please', 'the', 'that', 'over', 'to', 'towards', 'i', 'mean', 'sorry', 'no', 'wait') + VERBS \
    + COLORS + LEFT_WORDS + RIGHT_WORDS + NOUNS
WORDS = tuple(dict.fromkeys(WORDS))
VOCAB = {w: i for i, w in enumerate(WORDS)}
MAX_LEN = 20
HELD_OUT = {('blue', 'right'), ('red', 'left')}      # colour x side combinations never seen in a conjunction during training


@dataclass
class Utterance:
    """One sentence in a scene.

    Attributes
    ----------
    image : (16, 3) array
        Noisy one-hot colour strip.
    text : str
    tokens : list of int
        ``<bos>`` + word ids + ``<eos>``.
    cells, colors : list
        Cell and colour index of each object (left to right).
    valid : list of int
        Cells the sentence is true of (more than one means ambiguous).
    target : int
        The cell the speaker means, drawn uniformly from ``valid``.
    kind : str
        ``simple``, ``polite``, ``conjunction``, ``correction`` (an instruction, a correction marker and a second reference), ``followup``
        (only the correction part, "no, the left one") or ``ambiguous``.
    combo : tuple or None
        (colour, side) of a conjunction, else ``None``.
    """
    image: np.ndarray
    text: str
    tokens: list
    cells: list
    colors: list
    valid: list
    target: int
    kind: str
    combo: tuple = None

    @property
    def ambiguous(self):
        return len(self.valid) > 1


def cell_centres(n=N_CELLS):
    return -1.0 + 2.0 * (np.arange(n) + 0.5) / n


def encode(text):
    return [VOCAB['<bos>']] + [VOCAB[w] for w in text.split()] + [VOCAB['<eos>']]


def decode(tokens):
    return ' '.join(WORDS[t] for t in tokens if WORDS[t] not in ('<pad>', '<bos>', '<eos>'))


def _referents(word, cells, colors):
    """Indices (into the left-to-right object list) that a descriptor word is true of."""
    if word in COLORS:
        return [i for i, c in enumerate(colors) if COLORS[c] == word]
    if word in LEFT_WORDS:
        return [0]
    return [len(cells) - 1]


def _descriptors(i, cells, colors):
    """Descriptor words true of object ``i``."""
    out = [COLORS[colors[i]]]
    if i == 0:
        out += list(LEFT_WORDS)
    if i == len(cells) - 1:
        out += list(RIGHT_WORDS)
    return out


def _pick(rng, options):
    return options[int(rng.integers(len(options)))]


def sample_utterance(rng, split='train', pixel_noise=0.1):
    """Draw a scene, a sentence and its ground truth.

    ``split='heldout'`` draws only conjunctions with the held-out colour-side combinations."""
    while True:
        k = int(rng.integers(2, 4))
        cells = sorted(rng.choice(N_CELLS, k, replace=False).tolist())
        if min(np.diff(cells)) < 2:
            continue
        colors = rng.integers(0, 3, k).tolist()
        break
    img = pixel_noise * rng.standard_normal((N_CELLS, 3))
    for c, col in zip(cells, colors):
        img[c, col] += 1.0
    verb, prep, noun = _pick(rng, VERBS), _pick(rng, PREPS), _pick(rng, NOUNS)
    det = _pick(rng, ('the', 'the', 'that'))
    head = '%s %s' % (verb, prep)
    kind, combo = None, None
    if split == 'heldout':
        for _ in range(200):                                   # a conjunction whose (colour, side) is held out and true of an object
            col, side = _pick(rng, sorted(HELD_OUT))
            i = 0 if side == 'left' else k - 1
            if COLORS[colors[i]] == col:
                word = _pick(rng, LEFT_WORDS if side == 'left' else RIGHT_WORDS)
                text = '%s the %s %s %s' % (head, col, word, noun)
                valid, kind, combo = [i], 'conjunction', (col, side)
                break
        else:
            return sample_utterance(rng, split, pixel_noise)
    else:
        r = rng.random()
        t = int(rng.integers(k))
        unique = [w for w in _descriptors(t, cells, colors) if len(_referents(w, cells, colors)) == 1]
        pool = unique if (unique and rng.random() < 0.85) else _descriptors(t, cells, colors)
        if r < 0.36:
            w = _pick(rng, pool)
            text, valid, kind = '%s %s %s %s' % (head, det, w, noun), _referents(w, cells, colors), 'simple'
        elif r < 0.46:
            w = _pick(rng, pool)
            text, valid, kind = 'please %s %s %s %s' % (head, det, w, noun), _referents(w, cells, colors), 'polite'
        elif r < 0.57:
            side = 'left' if t == 0 else ('right' if t == k - 1 else None)
            if side is None or (COLORS[colors[t]], side) in HELD_OUT:
                w = _pick(rng, pool)
                text, valid, kind = '%s %s %s %s' % (head, det, w, noun), _referents(w, cells, colors), 'simple'
            else:
                word = _pick(rng, LEFT_WORDS if side == 'left' else RIGHT_WORDS)
                text = '%s the %s %s %s' % (head, COLORS[colors[t]], word, noun)
                valid, kind, combo = [t], 'conjunction', (COLORS[colors[t]], side)
        elif r < 0.67:
            w = _pick(rng, pool)
            text, valid, kind = '%s %s %s %s' % (_pick(rng, CORRECTIONS), det, w, noun), _referents(w, cells, colors), 'followup'
        elif r < 0.89:
            others = [i for i in range(k) if i != t]
            wrong = _pick(rng, others)
            wd = [w for w in _descriptors(wrong, cells, colors) if t not in _referents(w, cells, colors)]
            wd = wd or _descriptors(wrong, cells, colors)
            w1, w2 = _pick(rng, wd), _pick(rng, pool)
            text = '%s %s %s %s %s %s %s %s' % (head, det, w1, noun, _pick(rng, CORRECTIONS), det, w2, noun)
            valid, kind = _referents(w2, cells, colors), 'correction'
        else:
            text, valid, kind = '%s %s %s' % (head, det, noun), list(range(k)), 'ambiguous'
    target_obj = int(_pick(rng, valid))
    return Utterance(img, text, encode(text), cells, colors, [cells[i] for i in valid], cells[target_obj], kind, combo)


def make_corpus(n, seed, split='train'):
    rng = np.random.default_rng(seed)
    return [sample_utterance(rng, split) for _ in range(n)]


def batch(utterances, max_len=MAX_LEN):
    """Arrays for the model: padded tokens, lengths, images, target cells."""
    toks = np.zeros((len(utterances), max_len), np.int32)
    lens = np.zeros(len(utterances), np.int32)
    for i, u in enumerate(utterances):
        toks[i, :len(u.tokens)] = u.tokens
        lens[i] = len(u.tokens)
    return (toks, lens, np.stack([u.image for u in utterances]).astype(np.float32),
            np.array([u.target for u in utterances], np.int32))


def make_followup(u, rng, wrong=False):
    """A follow-up sentence about the same scene as ``u``: "no, the left one".

    It describes the object the speaker meant (``u.target``) unless ``wrong`` is true, in which case the speaker misspeaks and describes
    another object. The returned utterance keeps the scene and the speaker's true target, so the label is still what the speaker means.
    """
    k = len(u.cells)
    t = u.cells.index(u.target)
    obj = t
    if wrong and k > 1:
        obj = int(_pick(rng, [i for i in range(k) if i != t]))
    word = _pick(rng, _descriptors(obj, u.cells, u.colors))
    text = '%s the %s %s' % (_pick(rng, CORRECTIONS), word, _pick(rng, NOUNS))
    valid = [u.cells[i] for i in _referents(word, u.cells, u.colors)]
    return Utterance(u.image, text, encode(text), u.cells, u.colors, valid, u.target, 'followup')
